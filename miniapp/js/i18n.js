let currentLang = 'en';
let listeners = [];

export function initLang() {
  const saved = localStorage.getItem(LANG_KEY);
  if (saved && STRINGS[saved]) currentLang = saved;
  applyLang();
}

export function getLang() { return currentLang; }
export function getLangs() { return [{ code: 'en', label: 'English' }, { code: 'mr', label: 'मराठी' }, { code: 'hi', label: 'हिंदी' }]; }

export function setLang(code) {
  if (!STRINGS[code]) return;
  currentLang = code;
  localStorage.setItem(LANG_KEY, code);
  document.documentElement.lang = code;
  applyLang();
  listeners.forEach((fn) => fn(code));
}

export function t(key) { return STRINGS[currentLang]?.[key] || STRINGS.en[key] || key; }

export function onLangChange(fn) { listeners.push(fn); }
function applyLang() { document.documentElement.lang = currentLang; }
